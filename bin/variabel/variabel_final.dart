}

/*Kata Kunci final
Secara default, variable di Dart bisa dideklarasikan ulang, artinya jika sebelumnya kita membuat variable name dengan value "Eko", 
kita bisa ubah variable tersebut menjadi "Joko" dengan cara namaVariable = "Joko"
Kadang ada kasus dimana kita tidak ingin sebuah variable bisa dideklarasikan ulang, untuk
melakukan itu kita bisa gunakan kata kunci final:
final TipeData namaVariable = value;
